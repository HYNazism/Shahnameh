import React, { useState } from 'react';
import { GameLanguage } from '../data/i18nAndSettings';
import { soundEngine, SymphonicMode } from '../game/soundEngine';
import { Music, Play, Square, Sparkles, Download, Volume2 } from 'lucide-react';

interface MusicStudioModalProps {
  language: GameLanguage;
  onClose: () => void;
}

export const MusicStudioModal: React.FC<MusicStudioModalProps> = ({
  language,
  onClose,
}) => {
  const isFa = language !== 'en';
  const [activeMode, setActiveMode] = useState<SymphonicMode>(
    soundEngine.getSymphonicMode()
  );
  const [isPlaying, setIsPlaying] = useState<boolean>(soundEngine.isMusicPlaying());
  const [lyriaModel, setLyriaModel] = useState<'lyria-3-clip-preview' | 'lyria-3-pro-preview'>(
    'lyria-3-clip-preview'
  );
  const [prompt, setPrompt] = useState<string>(
    'Epic dark Persian orchestral battle music inspired by Ferdowsi Shahnameh, featuring hammered Santur, bowed Kamancheh, thunderous Daf and Tonbak war drums, and low brass Karna horns in Dastgah-e Chahargah'
  );
  const [loading, setLoading] = useState<boolean>(false);
  const [generatedAudioUrl, setGeneratedAudioUrl] = useState<string | null>(null);
  const [generatedLyrics, setGeneratedLyrics] = useState<string>('');
  const [statusMessage, setStatusMessage] = useState<string | null>(null);

  const handleSelectProceduralMode = (mode: SymphonicMode) => {
    setActiveMode(mode);
    soundEngine.startSymphonicSoundtrack(mode);
    setIsPlaying(true);
    setStatusMessage(
      isFa
        ? 'ارکستر سمفونیک و طبل رزم ایرانی (بلادرنگ بر روی تمام دستگاه‌ها) فعال شد.'
        : 'Real-time Persian Symphonic & War-Drum Soundtrack started.'
    );
  };

  const handleTogglePlay = () => {
    if (isPlaying) {
      soundEngine.stopSymphonicSoundtrack();
      setIsPlaying(false);
    } else {
      soundEngine.startSymphonicSoundtrack(activeMode);
      setIsPlaying(true);
    }
  };

  const handleGenerateLyriaMusic = async () => {
    setLoading(true);
    setStatusMessage(
      isFa
        ? `در حال ارسال درخواست تولید موسیقی به مدل ${lyriaModel}...`
        : `Requesting soundtrack generation from ${lyriaModel}...`
    );

    try {
      const response = await fetch('/api/music/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          prompt,
          model: lyriaModel,
        }),
      });

      const data = await response.json();
      if (!response.ok || data.error) {
        // Automatically start the built-in multi-layered Persian Symphonic engine as seamless fallback
        soundEngine.startSymphonicSoundtrack(activeMode);
        setIsPlaying(true);
        setStatusMessage(
          isFa
            ? `توجه: مدل ابری Lyria نیازمند کلید API پرداختی در بخش Settings > Secrets است (${data.error}). موتور سمفونیک داخلی شاهنامه (سنتور، کمانچه، دف و کرنا) به صورت خودکار و بدون محدودیت فعال شد!`
            : `Note: Cloud Lyria requires a paid API key in Settings > Secrets (${data.error}). Automatically activated the real-time Persian Symphonic War Orchestra!`
        );
      } else if (data.audioDataUrl) {
        setGeneratedAudioUrl(data.audioDataUrl);
        setGeneratedLyrics(data.lyrics || '');
        soundEngine.playLyriaTrack(data.audioDataUrl);
        setIsPlaying(true);
        setStatusMessage(
          isFa
            ? 'موسیقی حماسی با موفقیت توسط Lyria 3 تولید شد و در حال پخش در میدان نبرد است!'
            : 'Soundtrack generated by Lyria 3 and now playing in the arena!'
        );
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      soundEngine.startSymphonicSoundtrack(activeMode);
      setIsPlaying(true);
      setStatusMessage(
        isFa
          ? `موتور سمفونیک داخلی فعال شد (${msg}).`
          : `Activated built-in Persian Symphonic Orchestra (${msg}).`
      );
    } finally {
      setLoading(false);
    }
  };

  return (
    <div
      dir={isFa ? 'rtl' : 'ltr'}
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-[#070504]/92 pointer-events-auto"
      role="dialog"
      aria-modal="true"
      aria-labelledby="music-studio-title"
    >
      <div className="parchment-panel miniature-border w-full max-w-4xl p-6 md:p-8 text-[#F5E6C8] max-h-[92vh] overflow-y-auto">
        <div className="flex flex-wrap items-center justify-between gap-4 pb-4 border-b border-[#D97706]/35">
          <div>
            <div className="text-xs font-mono text-[#F59E0B] uppercase tracking-wider">
              PERSIAN SYMPHONIC WAR ORCHESTRA &amp; LYRIA 3 AI MUSIC STUDIO
            </div>
            <h2
              id="music-studio-title"
              className="font-display text-xl md:text-2xl font-bold text-[#FDE68A] mt-1"
            >
              {isFa
                ? 'تالار موسیقی حماسی شاهنامه (ارکستر سنتور، کمانچه، دف و هوش مصنوعی Lyria 3)'
                : 'Shahnameh Symphonic Soundtrack & Lyria 3 Music Generator'}
            </h2>
          </div>

          <button
            onClick={onClose}
            className="px-4 py-2 bg-[#991B1B] hover:bg-[#B91C1C] border border-[#F59E0B] text-xs font-bold text-[#FDE68A] cursor-pointer"
          >
            {isFa ? 'بستن [Esc]' : 'Close [Esc]'}
          </button>
        </div>

        {/* Section 1: Instant Built-In Multi-Layered Persian Symphonic Modes (Zero API Key Needed) */}
        <div className="mt-5 bg-[#120F0D]/95 border border-[#D97706]/50 p-5">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <h3 className="font-display text-base font-bold text-[#FDE68A] flex items-center gap-2">
                <Volume2 className="w-4 h-4 text-[#F59E0B]" />
                <span>
                  {isFa
                    ? '۱. ارکستر سمفونیک بلادرنگ شاهنامه (پخش فوری روی موبایل و کامپیوتر)'
                    : '1. Real-Time Persian Symphonic War Orchestra (Instant On All Devices)'}
                </span>
              </h3>
              <p className="text-xs text-[#D6C7B2] mt-1">
                {isFa
                  ? 'ترکیب چندلایه سنتور، کمانچه، طبل‌های جنگی دف و تنبک، و شیپور کرنا بر اساس دستگاه‌های موسیقی اصیل ایرانی:'
                  : 'Multi-layered synthesis of Santur, Kamancheh, Daf war drums, and Karna brass horns:'}
              </p>
            </div>

            <button
              onClick={handleTogglePlay}
              className={`px-4 py-2 border text-xs font-bold flex items-center gap-2 cursor-pointer ${
                isPlaying
                  ? 'bg-[#991B1B] border-[#FDE68A] text-[#FDE68A]'
                  : 'bg-[#065F46] border-[#34D399] text-[#D1FAE5]'
              }`}
            >
              {isPlaying ? <Square className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
              <span>
                {isPlaying
                  ? isFa
                    ? 'توقف موسیقی متن'
                    : 'Stop Soundtrack'
                  : isFa
                  ? 'پخش موسیقی متن حماسی'
                  : 'Play Epic Soundtrack'}
              </span>
            </button>
          </div>

          <div className="mt-4 grid grid-cols-1 md:grid-cols-3 gap-3">
            <button
              onClick={() => handleSelectProceduralMode('chahargah_war')}
              className={`p-3.5 border text-start cursor-pointer ${
                activeMode === 'chahargah_war'
                  ? 'bg-[#D97706]/25 border-[#FDE68A] text-[#FDE68A]'
                  : 'bg-[#080605] border-[#D97706]/35 text-[#D6C7B2] hover:border-[#F59E0B]'
              }`}
            >
              <div className="font-bold text-xs">
                {isFa ? 'دستگاه چهارگاه · رزم پهلوانان و آتش سده' : 'Dastgah-e Chahargah · Heroic War'}
              </div>
              <div className="text-[11px] text-[#A89882] mt-1">
                {isFa
                  ? 'ریتم کوبنده ۱۳۶ ضرب با سنتور حماسی، دف جنگی و شیپور کرنا'
                  : '136 BPM heroic war drums, Santur arpeggios & Karna brass'}
              </div>
            </button>

            <button
              onClick={() => handleSelectProceduralMode('shur_epic')}
              className={`p-3.5 border text-start cursor-pointer ${
                activeMode === 'shur_epic'
                  ? 'bg-[#D97706]/25 border-[#FDE68A] text-[#FDE68A]'
                  : 'bg-[#080605] border-[#D97706]/35 text-[#D6C7B2] hover:border-[#F59E0B]'
              }`}
            >
              <div className="font-bold text-xs">
                {isFa ? 'دستگاه شور · حماسه البرز و سوگ سیامک' : 'Dastgah-e Shur · Alborz Chronicle'}
              </div>
              <div className="text-[11px] text-[#A89882] mt-1">
                {isFa
                  ? 'نوای رازآلود و پرشکوه سنتور و کمانچه در اوج قله البرز'
                  : 'Mystical Persian modal melody with deep resonant strings'}
              </div>
            </button>

            <button
              onClick={() => handleSelectProceduralMode('ahriman_doom')}
              className={`p-3.5 border text-start cursor-pointer ${
                activeMode === 'ahriman_doom'
                  ? 'bg-[#991B1B]/40 border-[#F87171] text-[#FECACA]'
                  : 'bg-[#080605] border-[#D97706]/35 text-[#D6C7B2] hover:border-[#F87171]'
              }`}
            >
              <div className="font-bold text-xs">
                {isFa ? 'خروش اهریمن و دیو سیاه (Heavy Doom)' : 'Ahrimanic Doom & Blood Choir'}
              </div>
              <div className="text-[11px] text-[#A89882] mt-1">
                {isFa
                  ? 'فرکانس‌های بم، کوبش سنگین طبل‌های دوزخی و گام تاریک اهریمنی'
                  : 'Dark Phrygian low brass, heavy war percussion & abyssal drone'}
              </div>
            </button>
          </div>
        </div>

        {/* Section 2: Google Lyria 3 AI Soundtrack Generator (lyria-3-clip-preview & lyria-3-pro-preview) */}
        <div className="mt-5 bg-[#120F0D]/95 border border-[#D97706]/50 p-5">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <h3 className="font-display text-base font-bold text-[#FDE68A] flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-[#F59E0B]" />
              <span>
                {isFa
                  ? '۲. تولید موسیقی اختصاصی با هوش مصنوعی Lyria 3 (مدل‌های Clip و Pro)'
                  : '2. Generate Custom Soundtrack with Google Lyria 3'}
              </span>
            </h3>

            <div className="flex items-center gap-2 text-xs">
              <button
                onClick={() => setLyriaModel('lyria-3-clip-preview')}
                className={`px-3 py-1 border font-mono cursor-pointer ${
                  lyriaModel === 'lyria-3-clip-preview'
                    ? 'bg-[#D97706] text-[#0B0908] border-[#FDE68A] font-bold'
                    : 'bg-[#080605] text-[#D6C7B2] border-[#D97706]/40'
                }`}
              >
                lyria-3-clip-preview (30s)
              </button>
              <button
                onClick={() => setLyriaModel('lyria-3-pro-preview')}
                className={`px-3 py-1 border font-mono cursor-pointer ${
                  lyriaModel === 'lyria-3-pro-preview'
                    ? 'bg-[#D97706] text-[#0B0908] border-[#FDE68A] font-bold'
                    : 'bg-[#080605] text-[#D6C7B2] border-[#D97706]/40'
                }`}
              >
                lyria-3-pro-preview (Full Track)
              </button>
            </div>
          </div>

          <div className="mt-3">
            <label className="block text-xs text-[#D6C7B2] mb-1">
              {isFa
                ? 'توصیف فضای موسیقی (سازبندی، ریتم و فضای شاهنامه):'
                : 'Music Generation Prompt:'}
            </label>
            <textarea
              rows={2}
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              className="w-full p-2.5 bg-[#080605] border border-[#D97706]/50 text-xs text-[#F5E6C8] font-mono dir-ltr text-left"
            />
          </div>

          <div className="mt-3 flex flex-wrap items-center gap-3">
            <button
              onClick={handleGenerateLyriaMusic}
              disabled={loading}
              className="px-5 py-2.5 bg-[#1E3A8A] hover:bg-[#1D4ED8] disabled:opacity-50 border border-[#FDE68A] text-xs font-bold text-[#FDE68A] flex items-center gap-2 cursor-pointer"
            >
              <Music className="w-4 h-4" />
              <span>
                {loading
                  ? isFa
                    ? 'در حال آهنگسازی...'
                    : 'Composing Track...'
                  : isFa
                  ? `تولید و پخش قطعه با ${lyriaModel}`
                  : `Generate & Play with ${lyriaModel}`}
              </span>
            </button>

            {generatedAudioUrl && (
              <a
                href={generatedAudioUrl}
                download="Shahnameh-Lyria3-Soundtrack.mp3"
                className="px-4 py-2.5 bg-[#065F46] border border-[#34D399] text-xs font-bold text-[#D1FAE5] flex items-center gap-1.5"
              >
                <Download className="w-3.5 h-3.5" />
                <span>{isFa ? 'دانلود فایل MP3' : 'Download MP3'}</span>
              </a>
            )}
          </div>

          {statusMessage && (
            <div className="mt-3 p-3 bg-[#080605] border border-[#D97706]/45 text-xs text-[#FDE68A]">
              {statusMessage}
            </div>
          )}

          {generatedAudioUrl && (
            <div className="mt-3">
              <audio controls src={generatedAudioUrl} className="w-full h-9" />
              {generatedLyrics && (
                <pre className="mt-2 p-2.5 bg-[#080605] border border-[#D97706]/30 text-[11px] text-[#D6C7B2] whitespace-pre-wrap">
                  {generatedLyrics}
                </pre>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
